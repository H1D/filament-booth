/**
 * harness.ts: starts the Vite dev server on a free port and a headless
 * Chromium, and gives a scripted page the few things every check needs:
 * dropping a file, reading a slider, and the stand-in's readout.
 */
import { chromium, type Browser, type Locator, type Page } from "playwright-core";
import { createServer, type ViteDevServer } from "vite";
import type { StandInReadout } from "../../dev/fakes";

export const CHROMIUM = "/usr/bin/chromium";

export interface Session {
  readonly page: Page;
  readonly origin: string;
  close(): Promise<void>;
}

export async function start(viewport = { width: 1440, height: 900 }): Promise<Session> {
  const server: ViteDevServer = await createServer({ logLevel: "error", server: { port: 0, host: "127.0.0.1" } });
  await server.listen();
  const address = server.httpServer?.address();
  if (address === null || address === undefined || typeof address === "string") throw new Error("the dev server has no port");
  const origin = `http://127.0.0.1:${address.port}`;
  const browser: Browser = await chromium.launch({ executablePath: CHROMIUM, headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ viewport, acceptDownloads: true });
  const page = await context.newPage();
  page.on("pageerror", (e) => { console.error("page error:", e.message); });
  return {
    page, origin,
    close: async () => { await browser.close(); await server.close(); },
  };
}

export async function openPanels(s: Session, { fresh }: { fresh: boolean }): Promise<void> {
  if (fresh) {
    await s.page.goto(`${s.origin}/dev/panels.html`);
    await s.page.evaluate(() => { localStorage.clear(); });
  }
  await s.page.goto(`${s.origin}/dev/panels.html`);
  await s.page.waitForSelector(".app");
}

/** Dispatches a real drop event carrying a file, on the window, as dropping from the desktop does. */
export async function dropFile(page: Page, name: string, content: "stl" | "gcode"): Promise<void> {
  await page.evaluate(({ name, content }) => {
    const file = content === "stl"
      ? (() => {
        const bytes = new Uint8Array(84 + 50);
        new DataView(bytes.buffer).setUint32(80, 1, true);
        return new File([bytes], name);
      })()
      : new File(["; generated by a slicer\nG1 X0 Y0 Z0.2 E0.1\n"], name);
    const transfer = new DataTransfer();
    transfer.items.add(file);
    for (const type of ["dragenter", "dragover", "drop"]) {
      window.dispatchEvent(new DragEvent(type, { dataTransfer: transfer, bubbles: true, cancelable: true }));
    }
  }, { name, content });
}

export const standIn = (page: Page): Promise<StandInReadout | null> => page.evaluate(() => window.standIn());

/** The number field of a slider, found by its accessible name. */
export function numberField(page: Page, name: string): Locator {
  return page.getByRole("textbox", { name: `${name} value`, exact: false }).first();
}

export async function setNumber(page: Page, name: string, value: string): Promise<void> {
  const field = numberField(page, name);
  await field.click();
  await field.fill(value);
  await field.press("Enter");
}

export function section(page: Page, id: string): Locator {
  return page.locator(`details.section[data-section="${id}"]`);
}

export async function openSection(page: Page, id: string): Promise<Locator> {
  const s = section(page, id);
  if ((await s.getAttribute("open")) === null) await s.locator("> summary").click();
  return s;
}
